def post(path, payload):
    req = urllib.request.Request(BASE + path, data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    with OPENER.open(req, timeout=60) as r:
        return json.load(r)


def get(path, timeout=15):
    with OPENER.open(BASE + path, timeout=timeout) as r:
        return json.load(r)


def main():
    if "--list" in sys.argv:
        for i, c in enumerate(CASES, 1):
            print(f"  {i:2d}. {c[0]:24s} {c[2]}x{c[3]}  refs={len(c[1])}")
        return 0
    n = int(sys.argv[1])
    title, refs, w, h, seed, cfg, prompt = CASES[n - 1]
    print(f"[{n:02d}] {title}   {w}x{h}  refs={len(refs)}")
    # ---- 通用约束（自动追加，勿删）----
    prompt = prompt + (
        "\n\n【通用约束】画面中不要出现参考图里的任何手持道具——"
        "不要游戏光盘、不要手柄、不要任何被拿在手里的物件，双手是空的；"
        "不要沿用参考图的黄绿色底色。")
    if len(refs) == 1:
        prompt = prompt + (
            "\n\n【通用约束二】画面里只有这一个人物、只有一个正面形象，"
            "不是角色设定表、不是三视图、不要分栏分屏。")
    # ---- 通用约束结束 ----
    # ---- 审美要求（自动追加，勿删）----
    prompt = prompt + (
        "\n\n【审美要求】在符合上述媒介特性的前提下：① 单色主导——全画由一个主色调统摄（冷调或暖调只选一个），其余颜色只作极小面积的对比点缀，避免多种饱和色平均用力；② 明暗结构——明确分出亮部、中间调与暗部三层，暗部里要有内容而不是死黑（平涂类画法则用色块的冷暖与明度差建立同样的层次）；③ 刻画方式——形体之间的过渡要柔和、有虚实变化，不要处处硬边平涂（该清晰的地方清晰、该虚过去的地方要敢于虚）；④ 构图——主体偏离正中、放在三分线附近，留出有呼吸感的空白，不要填满画面；⑤ 主次——视觉中心（脸、眼睛、手）最精致，向外逐渐放松；⑥ 气质——追求美术馆藏品与画册印刷般的沉静克制，而不是商品海报式的鲜艳饱满。")
    # ---- 审美要求结束 ----
    payload = {"prompt": prompt, "negative_prompt": " ",
               "steps": 35, "cfg": cfg, "width": w, "height": h,
               "seed": seed, "reference_images": [r[1] for r in refs],
               "ref_resolution": 0, "custom_canvas": True}
    try:
        r = post("/api/generate", payload)
    except urllib.error.HTTPError as e:
        print("  提交失败:", e.code, e.read().decode("utf-8", "replace")[:300]); return 1
    job = r.get("job_id")
    if not job:
        print("  被拒绝:", json.dumps(r, ensure_ascii=False)[:300]); return 1
    t0 = time.time()
    while time.time() - t0 < 1200:
        time.sleep(3)
        p = get(f"/api/progress/{job}")
        if p.get("status") != "running":
            break
    full = get(f"/api/jobs/{job}")
    imgs = (full.get("job") or {}).get("images") or []
    if not imgs:
        print("  无产物:", p.get("error")); return 1
    rel = imgs[0]["file"]
    src = os.path.join(HERE, "..", "outputs", rel.replace("/", os.sep))
    dst = os.path.join(OUT, f"{n:02d}_{title}.png")
    with open(src, "rb") as fi, open(dst, "wb") as fo:
        fo.write(fi.read())
    print(f"  OK {p.get('elapsed')}s -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
