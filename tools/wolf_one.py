def post(path, payload):
    req = urllib.request.Request(BASE + path, data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    with OPENER.open(req, timeout=60) as r:
        return json.load(r)


def get(path, timeout=15):
    with OPENER.open(BASE + path, timeout=timeout) as r:
        return json.load(r)


def main():
    if "--list" in sys.argv:
        for i, (t, w, h, s, _) in enumerate(CONCEPTS, 1):
            print(f"  {i:2d}. {t}   {w}x{h}  seed={s}")
        return 0
    if len(sys.argv) < 2:
        print("用法: python wolf_one.py <序号>  或  --list")
        return 1
    n = int(sys.argv[1])
    if not (1 <= n <= len(CONCEPTS)):
        print(f"序号需在 1..{len(CONCEPTS)}")
        return 1
    title, w, h, seed, prompt = CONCEPTS[n - 1]

    wf = {
        "1": {"class_type": "UNETLoader",
              "inputs": {"unet_name": "qwen_image_2.1_int8_convrot.safetensors",
                         "weight_dtype": "default"}},
        "2": {"class_type": "CLIPLoader",
              "inputs": {"clip_name": "qwen3vl_8b_int8_convrot.safetensors",
                         "type": "qwen_image", "device": "default"}},
        "3": {"class_type": "VAELoader",
              "inputs": {"vae_name": "qwen_image_2.1_vae_bf16.safetensors"}},
        "7": {"class_type": "EmptyLatentImage",
              "inputs": {"width": w, "height": h, "batch_size": 1}},
        "5": {"class_type": "TextEncodeQwenImage21",
              "inputs": {"clip": ["2", 0], "prompt": prompt, "negative_prompt": " ",
                         "vae": ["3", 0], "resolution": 0,
                         "images.image_1": ["10", 0]}},
        "6": {"class_type": "KSampler",
              "inputs": {"model": ["1", 0], "positive": ["5", 0], "negative": ["5", 1],
                         "latent_image": ["7", 0], "seed": seed, "steps": 35, "cfg": 1.0,
                         "sampler_name": "euler", "scheduler": "simple", "denoise": 1.0}},
        "10": {"class_type": "LoadImage", "inputs": {"image": REF}},
        "8": {"class_type": "VAEDecode", "inputs": {"samples": ["6", 0], "vae": ["3", 0]}},
        "9": {"class_type": "SaveImage",
              "inputs": {"images": ["8", 0], "filename_prefix": f"wolf/{n:02d}"}},
    }
    print(f"[{n:02d}] {title}   {w}x{h}  seed={seed}")
    try:
        resp = post("/prompt", {"prompt": wf, "client_id": "wolf"})
    except urllib.error.HTTPError as e:
        print("  提交失败:", e.code, e.read().decode("utf-8", "replace")[:400])
        return 1
    pid = resp.get("prompt_id")
    if not pid:
        print("  被拒绝:", json.dumps(resp, ensure_ascii=False)[:300])
        return 1
    t0 = time.time()
    while time.time() - t0 < 1800:
        time.sleep(3)
        e = get(f"/history/{pid}").get(pid)
        if e:
            st = e.get("status", {}).get("status_str")
            if st == "success":
                for o in (e.get("outputs") or {}).values():
                    for im in (o.get("images") or []):
                        rel = os.path.join(im.get("subfolder", ""), im["filename"])
                        src = os.path.join(COMFY_OUT, rel)
                        dst = os.path.join(OUT, f"{n:02d}_{title}.png")
                        with open(src, "rb") as fi, open(dst, "wb") as fo:
                            fo.write(fi.read())
                        print(f"  OK {time.time()-t0:.0f}s -> {dst}")
                return 0
            if st == "error":
                for m in e.get("status", {}).get("messages", []):
                    if isinstance(m, list) and len(m) >= 2 and m[0] == "execution_error":
                        d = m[1] or {}
                        print(f"  ERROR {d.get('node_type')}: {d.get('exception_message')}")
                return 1
    print("  超时")
    return 1


if __name__ == "__main__":
    sys.exit(main())
